export function normalizeFolderName(name) {
  return name
    .toLowerCase()
    .replace(/\u2013/g, "-")
    .replace(/\u2014/g, "-")
    .replace(/\s+/g, " ")
    .trim();
}

export function resolveDriveCategory(folderName) {
  const key = normalizeFolderName(folderName);
  return DRIVE_CATEGORY_MAP[key] ?? null;
}

export function extractProductName(folderName) {
  const cleaned = folderName.replace(/^\d+[a-z]*-?\s*/i, "").trim();
  return cleaned || folderName;
}

export function isCopyImage(filename) {
  const lower = filename.toLowerCase();
  return (
    lower.includes("نسخة") ||
    lower.includes("copy of") ||
    lower.startsWith("copy ")
  );
}

export function rankImage(filename) {
  const lower = filename.toLowerCase();
  if (isCopyImage(filename)) return 100;
  if (lower.endsWith(".pdf")) return 999;
  if (/^\d+\s*\(\d+\)/.test(lower) || /^\d+\.jpg/.test(lower)) return 1;
  if (lower.includes("gallon")) return 2;
  if (lower.includes("drum")) return 3;
  return 10;
}

export function selectBestImages(imageEntries) {
  if (imageEntries.length === 0) return [];

  const nonCopies = imageEntries.filter((img) => !isCopyImage(img.name));
  const pool = nonCopies.length > 0 ? nonCopies : imageEntries;

  const sorted = [...pool].sort((a, b) => {
    const rankDiff = rankImage(a.name) - rankImage(b.name);
    if (rankDiff !== 0) return rankDiff;
    return b.size - a.size;
  });

  const seen = new Set();
  const urls = [];
  for (const img of sorted) {
    const url = `/catalog/${img.rel.replace(/\\/g, "/")}`;
    if (!seen.has(url)) {
      seen.add(url);
      urls.push(url);
    }
  }
  return urls;
}
